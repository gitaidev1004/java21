package com.example.app;
/**
 * Calculator 클래스는 두 정수의 합과 곱을 계산하는 예제입니다.
 * @author Kim
 * @version 1.0
 */
public class Calculator {
    // 한 줄 주석: 두 정수의 합을 반환합니다.
    public int add(int a, int b) {
        return a + b;  // 결과를 반환
    }

    /*
     * 블록 주석:
     * 아래 메서드는 두 수의 곱을 반환합니다.
     * 이 주석은 여러 줄에 걸친 설명이 필요할 때 사용합니다.
     */
    public int multiply(int a, int b) {
        return a * b;
    }
}
